# 데코레이터 : 함수가 함수를 받는다.. 다른 함수의 기능을 가져온다
# ㄴ 한마디로 함수를 불러오는 함수 
# 데코레이터는 기존 함수를 수정하지 않고, 함수에 새로운 기능을 추가하는 문법

def hello():
    print('안녕하세요.')

hello() #안녕하세요.

print("============== 1 ==================")
def deco(func):
    def wrapper():
        print("함수 실행 전")
        func()
        print("함수 실행 후")
    return wrapper

@deco
def hello2():
    print('안녕하세요2')

hello2()

# ============== 1 ==================
# 함수 실행 전
# 안녕하세요2
# 함수 실행 후


