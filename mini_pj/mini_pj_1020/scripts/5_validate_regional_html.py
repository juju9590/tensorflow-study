
# 지역별 html 본문 추출

from pathlib import Path
from bs4 import BeautifulSoup

# 1. HTML 샘플 폴더
input_dir = Path("C:/tensorflow_study/mini_pj/data/html_samples")

# 2. 전체 HTML 파일 가져오기
html_files = sorted(input_dir.rglob("*.html"))

print("전체 HTML 샘플 수:", len(html_files))

# 3. 지역별 HTML 검사
for file_path in html_files:

    region = file_path.parent.name

    # HTML 파일 읽기
    with open(file_path, "r", encoding="utf-8") as f:
        html = f.read()

    # HTML 분석
    soup = BeautifulSoup(html, "html.parser")

    # 불필요한 태그 제거
    for tag in soup(["script", "style"]):
        tag.decompose()

    # 텍스트 추출
    text = soup.get_text("\n", strip=True)

    # 발언자 구분 후보 찾기
    lines = text.splitlines()

    speakers = []

    for line in lines:
        if line.strip().startswith("○"):
            speakers.append(line.strip())

    # 결과 확인
    print("\n==============================")
    print("지역:", region)
    print("파일:", file_path.name)
    print("본문 글자 수:", len(text))
    print("발언자 후보 수:", len(speakers))

    if text:
        print("본문 추출: 성공")
    else:
        print("본문 추출: 실패")



