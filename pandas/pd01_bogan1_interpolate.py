'''
결측치  처리
1. 삭제  - 행 또는 열 전체 지우기 (dropna)
2. 임의의 값
    - 0 : fillna
    - 평균 : mean (데이터 내 이상치가 있을때 조심)
    - 중위값 : median (평균값 보단 안정적)
    - 앞의값 : ffill
    - 뒷의값 : bfill
    - 특정값 : 777 등 (조건 보고 넣어야 한다)
    - 최빈값 : 가장 많이 나오는 값
    기타 등등 ...
3. interpolate - 보간(알려진 데이터 점 집합의 범위 내에  새 데이터 점을 추가하는 기법)
4. 모델 : .predict(값을 예측해서), (전혀 다른 모델 사용)
5. 부스팅(트리) 계열 모델 : 통상 결측치, 이상치에 대해 영향을 덜 받는다. (자유롭다)
    ㄴ ex, xgboost 등의 모델 사용할때는 결측치 처리 안해도 된다...
    ㄴ 부스팅 모델에서 epochs 역할을 하는건? n_estimators
6. 스케일링(로브스트 등...) : 이상치에 자유로움.. 결측치는 처리해야 함

'''

